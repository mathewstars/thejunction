"""An example person whose focus sessions carry raw face frames, so the frame
reading (level 2 reads the frames, code checks every item) can be shown without
a recording of a real face.

    python -m clinic_engine.seed_frames

Every frame is GENERATED by frames_reference.make_session: a synthetic stream
with smiles planted at known places. It is example data and is marked so. The
six sessions tell one thing: in the first three the person smiles clearly
several times; in the last three the smiles are few and faint, under the fixed
rule's onset, so the rule counts none and the model's reading is where they
show. Nothing here is a measurement of a person.

With level 2 on, the script lets the model read each session (the reduced
stream of generated numbers goes out through the usual gates).
"""

from __future__ import annotations

import random
from datetime import datetime, time, timedelta, timezone
from zoneinfo import ZoneInfo

from .config import Settings
from .frames_reference import make_session
from .mind import face_features as ff
from .seed import create_patient, wipe_patient
from .service import _raw_object
from .store import Store, make_store

LABEL = "Example F-001"
NAME = "Leo Virtanen"
# (days ago, the smiles planted, in order)
SESSIONS = (
    (12, ["strong", "faint", "strong", "strong"]),
    (10, ["strong", "strong", "faint", "strong"]),
    (8, ["strong", "faint", "strong"]),
    (5, ["faint", "strong", "faint"]),
    (3, ["faint", "faint"]),
    (1, ["faint", "faint", "faint"]),
)


def session_ids() -> list[str]:
    return [f"example-frames-{k:03d}" for k in range(len(SESSIONS))]


def create(store: Store, clinic_id: str, tz_name: str, now: datetime, seed: int = 31) -> str:
    """Create the example person, or write their sessions again in place."""
    from .mind.activities import process_activity
    pid = None
    for key in store.list(f"clinics/{clinic_id}/patients/"):
        if key.endswith("/patient.json") and (store.get(key) or {}).get("label") == LABEL:
            pid = store.get(key)["id"]
    if pid is None:
        pid = create_patient(store, clinic_id, LABEL, tz_name, now, example=True,
                             allow_outside=True, display_name=NAME)
    else:
        wipe_patient(store, clinic_id, pid)
    base = f"clinics/{clinic_id}/patients/{pid}/"
    tz = ZoneInfo(tz_name)
    today = now.astimezone(tz).date()
    rng = random.Random(seed)
    previous: list[dict] = []
    for k, (ago, wanted) in enumerate(SESSIONS):
        raw, _truth = make_session(seed * 100 + k, wanted=wanted, moments=True)
        started = datetime.combine(today - timedelta(days=ago), time(15, 10 + k), tzinfo=tz)
        n = rng.randint(16, 20)
        slow = 1.0 + 0.06 * k  # reactions get a little slower over the two weeks
        a = {"id": session_ids()[k], "type": "focus",
             "started_at": started.astimezone(timezone.utc).isoformat(), "suggestion_id": None,
             "duration_s": 45.0, "completed": True, "ended_by": "finished",
             "correct_taps": n - 1, "wrong_taps": 1, "misses": rng.randint(1, 3),
             "reaction_ms": [int(max(200, rng.gauss(520, 55) * slow)) for _ in range(n)],
             "face": ff.summarize(raw), "face_source": "raw", "face_raw_info": ff.describe(raw)}
        rec = process_activity(a, previous)
        rec.update(example=True, received_at=a["started_at"], content_sha256="example",
                   crisis=False, analysis={"status": "off"}, frames_reading={"status": "pending"})
        store.put(base + f"activities/{rec['id']}.json", rec)
        store.put(base + f"faceraw/{rec['id']}.json", _raw_object(a, raw, now))
        previous.append(rec)
    return pid


def main() -> None:
    import asyncio

    from .app import create_app
    settings = Settings.from_env()
    store = make_store(settings)
    st = store.get("demo/state.json")
    if not st:
        raise SystemExit("No demo in this store yet. Run the seed first.")
    c = st["clinic_id"]
    tz_name = store.get(f"clinics/{c}/patients/{st['patient_id']}/patient.json")["timezone"]
    pid = create(store, c, tz_name, datetime.now(timezone.utc))
    mind = create_app(settings=settings, store=store, start_ticker=False).state.ctx.mind
    repo = mind.repo(c, pid)
    done = []
    for aid in session_ids():
        res = asyncio.run(mind.run_frames_reading(repo, aid, take_lock=True))
        ag = res.get("agreement") or {}
        done.append(f"{res['status']}"
                    + (f" (code {ag.get('smiles_code')}, model only {ag.get('smiles_faint')})"
                       if res["status"] == "ready" else ""))
    print(f"Face frames example ready: {NAME} ({LABEL}), {len(SESSIONS)} generated sessions. "
          f"Patient id: {pid}. Frame readings: {', '.join(done)}")


if __name__ == "__main__":
    main()
