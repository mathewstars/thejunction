"""How often the Revontulet own normal calls a game unusual when nothing has
changed, and how often it catches the slide built into the example.

    python -m clinic_engine.revontulet_check [--runs 3000]

Everything is GENERATED by seed_revontulet._game, whose speeds and game-to-game
variation are set from the first real games the team has (one person, one
evening). It says how the rules behave on that generator, not on people.
"Spread" scales the game-to-game variation: 1.0 is as in those real games.

Three rules are measured, all on the two speeds the clinician page compares
(the choice of the harder crack and the time to choose are never labelled):

1. One game against the games just before it (the moving reference).
2. One game against the person's start, games 3 to 12 (the fixed reference).
3. The last three games together against the start (the page's headline): a
   counting rule with no tuned number, see _three_together.

For each: how often a person who does not change still gets a label, and how
often the example's slide (speeds falling by over a third from week five) is
labelled at its end: the single-game rules on its last three games, the
three-together rule on the three looks that end in those games.
"""

from __future__ import annotations

import argparse
import random

from .mind.activities import _stats, _z, revontulet_features
from .mind.thresholds import T
from .seed_revontulet import PER_WEEK, SLIDE, WEEKS, _game

LABELLED = ("trace_speed_cm_s", "stroke_speed_cm_s")   # the two the page labels per game
CUT = T.revontulet_unusual_z
NEED = T.revontulet_baseline_min
START = slice(T.revontulet_start_from, T.revontulet_start_to)  # games 3 to 12


def _series(rng: random.Random, slides: list[float], spread: float = 1.0) -> list[dict]:
    return [revontulet_features({"revontulet": _game(rng, s, spread)}) for s in slides]


def _moving_z(games: list[dict], k: int, name: str) -> float | None:
    earlier = [g[name] for g in games[:k] if g.get(name) is not None][-T.activity_baseline_max:]
    if len(earlier) < NEED:
        return None
    return _z(games[k].get(name), _stats(earlier, name, T))


def _start_z(games: list[dict], k: int, name: str) -> float | None:
    vals = [g[name] for g in games[START] if g.get(name) is not None]
    if k < START.stop or len(vals) < NEED:
        return None
    return _z(games[k].get(name), _stats(vals, name, T))


def _three_together(games: list[dict], k: int, name: str = "trace_speed_cm_s") -> int:
    """The page's headline rule, by counting and with no tuned number: -1 when
    each of the last three games is slower than all start games but at most one,
    +1 when each is faster than all but at most one, else 0. If nothing changes
    and games are independent, either happens in 8 of 286 looks (2.8%)."""
    start = sorted(g[name] for g in games[START] if g.get(name) is not None)
    last = [g[name] for g in games[k - 2:k + 1] if g.get(name) is not None]
    if k - 2 < START.stop or len(start) < START.stop - START.start or len(last) < 3:
        return 0   # all ten start games must have a speed: with fewer the chance figure is higher
    if all(v < start[1] for v in last):
        return -1
    if all(v > start[-2] for v in last):
        return 1
    return 0


def _run_of_three(flags: list[bool]) -> bool:
    return any(flags[i] and flags[i + 1] and flags[i + 2] for i in range(len(flags) - 2))


def _off(z: float | None) -> bool:
    return z is not None and abs(round(z, 1)) >= CUT


def run(runs: int = 3000, seed: int = 7, spread: float = 1.0) -> dict:
    rng = random.Random(seed)
    n = WEEKS * len(PER_WEEK)
    flat = [0.0] * n
    slide = [SLIDE[w] for w in range(WEEKS) for _ in PER_WEEK]
    late = range(n - 3, n)   # the last three games, at the bottom of the slide
    recent = games = start = start_games = either = 0
    recent_runs = start_runs = 0
    pooled = pooled_looks = pooled_people = pooled_caught = 0
    per = {name: 0 for name in LABELLED}
    mov = fix = late_games = 0
    for _ in range(runs):
        g = _series(rng, flat, spread)
        r_flags, s_flags, ever = [], [], False
        for k in range(NEED, n):
            hit = {name: _off(_moving_z(g, k, name)) for name in LABELLED}
            s_hit = any(_off(_start_z(g, k, name)) for name in LABELLED)
            games += 1
            recent += any(hit.values())
            either += any(hit.values()) or s_hit
            r_flags.append(any(hit.values()))
            for name in LABELLED:
                per[name] += hit[name]
            if k >= START.stop:
                start_games += 1
                start += s_hit
                s_flags.append(s_hit)
            if k - 2 >= START.stop:
                pooled_looks += 1
                if _three_together(g, k):
                    pooled += 1
                    ever = True
        pooled_people += ever
        recent_runs += _run_of_three(r_flags)
        start_runs += _run_of_three(s_flags)
        g = _series(rng, slide, spread)
        for k in late:   # single games: the last three; three together: the looks ending in them
            late_games += 1
            zm, zf = _moving_z(g, k, "trace_speed_cm_s"), _start_z(g, k, "trace_speed_cm_s")
            mov += zm is not None and round(zm, 1) <= -CUT
            fix += zf is not None and round(zf, 1) <= -CUT
            pooled_caught += _three_together(g, k) == -1
    return {"runs": runs, "unchanged_recent_label": round(recent / games, 3),
            "unchanged_per_measure": {k: round(v / games, 3) for k, v in per.items()},
            "unchanged_start_label": round(start / start_games, 3),
            "unchanged_any_label": round(either / games, 3),
            "unchanged_people_three_in_a_row_recent": round(recent_runs / runs, 3),
            "unchanged_people_three_in_a_row_start": round(start_runs / runs, 3),
            "unchanged_pooled_label": round(pooled / pooled_looks, 3),
            "unchanged_people_pooled_ever": round(pooled_people / runs, 3),
            "slide_last_three_tracing_slower_recent": round(mov / late_games, 3),
            "slide_last_three_tracing_slower_start": round(fix / late_games, 3),
            "slide_last_three_together_slower": round(pooled_caught / late_games, 3)}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--runs", type=int, default=3000)
    args = ap.parse_args()
    print(f"Generated data, {args.runs} runs of 24 games per row. Spread 1 is the game-to-game variation of")
    print("the first real games. 'Unchanged': shares that carry a label when nothing changes. 'Slide': how")
    print("often the example's slide is labelled slower in tracing in its last three games.")
    print(f"{'spread':>6} | unchanged games: {'recent':>6} {'start':>6} {'either':>6} | 3 in a row: {'recent':>6} "
          f"{'start':>6} | last three together: {'looks':>6} {'people':>6} | slide: {'recent':>6} {'start':>6} "
          f"{'three':>6}")
    for spread in (0.5, 1.0, 1.5, 2.0):
        o = run(args.runs, spread=spread)
        print(f"{spread:>6.1f} | {'':17}{o['unchanged_recent_label']:>6.0%} {o['unchanged_start_label']:>6.0%} "
              f"{o['unchanged_any_label']:>6.0%} | {'':12}{o['unchanged_people_three_in_a_row_recent']:>6.0%} "
              f"{o['unchanged_people_three_in_a_row_start']:>6.0%} | {'':21}{o['unchanged_pooled_label']:>6.0%} "
              f"{o['unchanged_people_pooled_ever']:>6.0%} | {'':7}{o['slide_last_three_tracing_slower_recent']:>6.0%} "
              f"{o['slide_last_three_tracing_slower_start']:>6.0%} {o['slide_last_three_together_slower']:>6.0%}")


if __name__ == "__main__":
    main()
