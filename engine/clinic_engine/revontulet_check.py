"""How often the Revontulet own normal calls a game unusual when nothing has
changed, and how often it catches the slide built into the example.

    python -m clinic_engine.revontulet_check [--runs 3000]

Everything is GENERATED by seed_revontulet._game; it says how the method
behaves on that generator, not on people. Real play varies more from game to
game than the generator does, so on people the first number would differ.

Two questions, for the two measures the clinician page labels per game
(tracing speed and stroke speed; the choice of the harder crack and the time to
choose are judged over several games, never per game):

1. A person who does not change (24 games, slide 0): what share of games from
   the ninth on carry at least one "unusual" label (2.0 or more either way)?
2. The example's slide (weeks five to eight): in the last two weeks, what share
   of games are labelled slower in tracing, against the moving range (the 20
   games before) and against the fixed start (games 3 to 12)?
"""

from __future__ import annotations

import argparse
import random

from .mind.activities import _stats, _z, revontulet_features
from .mind.thresholds import T
from .seed_revontulet import PER_WEEK, SLIDE, WEEKS, _game

LABELLED = ("trace_speed_cm_s", "stroke_speed_cm_s")   # the two the page labels per game
CUT = T.revontulet_unusual_z
NEED = T.revontulet_baseline_min
START = slice(T.revontulet_start_from, T.revontulet_start_to)  # games 3 to 12


def _series(rng: random.Random, slides: list[float]) -> list[dict]:
    return [revontulet_features({"revontulet": _game(rng, s)}) for s in slides]


def _moving_z(games: list[dict], k: int, name: str) -> float | None:
    earlier = [g[name] for g in games[:k] if g.get(name) is not None][-T.activity_baseline_max:]
    if len(earlier) < NEED:
        return None
    return _z(games[k].get(name), _stats(earlier, name, T))


def _start_z(games: list[dict], k: int, name: str) -> float | None:
    vals = [g[name] for g in games[START] if g.get(name) is not None]
    if k < START.stop or len(vals) < NEED:
        return None
    return _z(games[k].get(name), _stats(vals, name, T))


def _run_of_three(flags: list[bool]) -> bool:
    return any(flags[i] and flags[i + 1] and flags[i + 2] for i in range(len(flags) - 2))


def _off(z: float | None) -> bool:
    return z is not None and abs(round(z, 1)) >= CUT


def run(runs: int = 3000, seed: int = 7) -> dict:
    rng = random.Random(seed)
    n = WEEKS * len(PER_WEEK)
    flat = [0.0] * n
    slide = [SLIDE[w] for w in range(WEEKS) for _ in PER_WEEK]
    late = range(n - 2 * len(PER_WEEK), n)
    recent = games = start = start_games = either = 0
    recent_runs = start_runs = 0
    per = {name: 0 for name in LABELLED}
    mov = fix = late_games = 0
    for _ in range(runs):
        g = _series(rng, flat)
        r_flags, s_flags = [], []
        for k in range(NEED, n):
            hit = {name: _off(_moving_z(g, k, name)) for name in LABELLED}
            s_hit = any(_off(_start_z(g, k, name)) for name in LABELLED)
            games += 1
            recent += any(hit.values())
            either += any(hit.values()) or s_hit
            r_flags.append(any(hit.values()))
            for name in LABELLED:
                per[name] += hit[name]
            if k >= START.stop:
                start_games += 1
                start += s_hit
                s_flags.append(s_hit)
        recent_runs += _run_of_three(r_flags)
        start_runs += _run_of_three(s_flags)
        g = _series(rng, slide)
        for k in late:
            late_games += 1
            zm, zf = _moving_z(g, k, "trace_speed_cm_s"), _start_z(g, k, "trace_speed_cm_s")
            mov += zm is not None and round(zm, 1) <= -CUT
            fix += zf is not None and round(zf, 1) <= -CUT
    return {"runs": runs, "unchanged_recent_label": round(recent / games, 3),
            "unchanged_per_measure": {k: round(v / games, 3) for k, v in per.items()},
            "unchanged_start_label": round(start / start_games, 3),
            "unchanged_any_label": round(either / games, 3),
            "unchanged_people_three_in_a_row_recent": round(recent_runs / runs, 3),
            "unchanged_people_three_in_a_row_start": round(start_runs / runs, 3),
            "slide_last_two_weeks_tracing_slower_moving": round(mov / late_games, 3),
            "slide_last_two_weeks_tracing_slower_start": round(fix / late_games, 3)}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--runs", type=int, default=3000)
    out = run(ap.parse_args().runs)
    print(f"Generated data, {out['runs']} runs of 24 games. Nothing changes:")
    print(f"  against the recent games, {out['unchanged_recent_label']:.0%} of games from the ninth on "
          f"carry a label (" + ", ".join(f"{k} {v:.0%}" for k, v in out["unchanged_per_measure"].items())
          + f"); {out['unchanged_people_three_in_a_row_recent']:.0%} of people get three such games in a row.")
    print(f"  against the start, {out['unchanged_start_label']:.0%} of games from the thirteenth on carry "
          f"a label; {out['unchanged_people_three_in_a_row_start']:.0%} of people get three in a row.")
    print(f"  either label: {out['unchanged_any_label']:.0%} of games from the ninth on.")
    print(f"The example's slide, last two weeks: tracing labelled slower in "
          f"{out['slide_last_two_weeks_tracing_slower_moving']:.0%} of games against the moving "
          f"range and {out['slide_last_two_weeks_tracing_slower_start']:.0%} against the fixed start.")


if __name__ == "__main__":
    main()
